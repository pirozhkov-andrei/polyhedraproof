"""The status of one audit target from its new attempt (specification §11.2).

**Strict profile**. A new proof is comparable with the historical one only when the
fields that determine the proof bytes are equal between the source snapshot
(``target.machinery``) and the snapshot of the audit attempt:

- route ``cdcl``: ``solver.sha256``, ``solver.argv``, ``runtime.platform``, ``runtime.libc``;
- route ``unit``: ``unit_algorithm`` and ``cubeproof_sha256`` (the unit proof is generated by
  this package).

Other differences (Python, image digest, checker, helper, package sources, solver version
text) are *reported* in the reason but do not prevent a match.

**Status of an executed attempt** (:func:`classify_attempt`), first applicable row wins:

1. the attempt is not an attempt of this target (node, CNF hash, route): FAILED
   ``attempt_mismatch``;
2. MODEL: the target the certificate used as proved has a valid model (the journal reader has
   checked it against CNF(F, C)): FAILED ``inconsistent_model`` -- an inconsistency, never
   NOT_COMPARABLE, whatever the limits, profile or admission of the run that found it;
3. a CDCL attempt with a solver time limit (``solver_time_ms`` must be null): FAILED
   ``attempt_mismatch``;
4. machinery not admitted by the campaign: FAILED ``checker_not_admitted`` /
   ``solver_not_admitted``;
5. INVALID_MODEL: FAILED ``invalid_model``; TOOL_FAILED: FAILED ``tool_failed``;
   CHECK_REJECTED: FAILED ``rejected``; EXHAUSTED: OPEN;
6. VERIFIED_UNSAT with the strict profile: HASH_MATCHED if ``proof_sha256`` is the
   historical one, else MISMATCH (even though the new proof passed);
7. VERIFIED_UNSAT with another profile: REPROVED_UNSAT (never a historical match).

**Not comparable** (:func:`classify_unavailable`): a strict audit runs only the source solver
binary with the source argv; a CDCL target whose source solver is not the configured one is
NOT_COMPARABLE without a run (:func:`strict_runnable`).

**Exit class** (specification §12.2): MISMATCH and FAILED
``attempt_mismatch``/``inconsistent_model``/``rejected`` are integrity failures (4); other FAILED
causes are tool failures (5); OPEN, NOT_COMPARABLE and REPROVED_UNSAT leave the audit incomplete
(1); HASH_MATCHED is success (0). A FAILED reason starts with its code followed by ``": "`` and a
detail.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

from cubeproof.contracts.campaign import Admit
from cubeproof.contracts.enums import AuditStatus, ExitCode, Outcome, Route
from cubeproof.evidence.certify.admission import admission_reason
from cubeproof.evidence.schema import Attempt, AuditTarget, Machinery

__all__ = [
    "INTEGRITY_FAILURES",
    "TOOL_FAILURES",
    "Classified",
    "classify_attempt",
    "classify_unavailable",
    "exit_class",
    "failure_code",
    "profile_differences",
    "reported_differences",
    "strict_runnable",
]

#: FAILED codes that are integrity failures (exit 4); every other FAILED code is a tool one.
INTEGRITY_FAILURES = frozenset({"attempt_mismatch", "inconsistent_model", "rejected"})
TOOL_FAILURES = frozenset(
    {"checker_not_admitted", "solver_not_admitted", "invalid_model", "tool_failed"}
)

_STRICT: dict[Route, tuple[str, ...]] = {
    Route.CDCL: ("solver.sha256", "solver.argv", "runtime.platform", "runtime.libc"),
    Route.UNIT: ("unit_algorithm", "cubeproof_sha256"),
}
_REPORTED = (
    "solver.sha256",
    "solver.argv",
    "solver.version",
    "checker.sha256",
    "helper",
    "runtime.python",
    "runtime.libc",
    "runtime.platform",
    "runtime.image_digest",
    "packages_sha256",
    "cubeproof_sha256",
    "unit_algorithm",
)


@dataclass(frozen=True)
class Classified:
    """An audit_result's ``status`` and ``reason``."""

    status: AuditStatus
    reason: str


def _field(machinery: Machinery, name: str) -> Any:
    value: Any = machinery.to_json()
    for part in name.split("."):
        value = value[part]
    return value


def _differences(
    target: AuditTarget, machinery: Machinery, names: Sequence[str]
) -> tuple[str, ...]:
    return tuple(n for n in names if _field(target.machinery, n) != _field(machinery, n))


def profile_differences(target: AuditTarget, machinery: Machinery) -> tuple[str, ...]:
    """The strict-profile fields in which the audit snapshot differs from the source."""
    return _differences(target, machinery, _STRICT[Route(target.route)])


def reported_differences(target: AuditTarget, machinery: Machinery) -> tuple[str, ...]:
    """Every other machinery difference: reported, without effect on the status."""
    strict = set(_STRICT[Route(target.route)])
    return tuple(n for n in _differences(target, machinery, _REPORTED) if n not in strict)


def _with_reported(text: str, target: AuditTarget, machinery: Machinery) -> str:
    other = reported_differences(target, machinery)
    note = f"reported differences: {', '.join(other)}" if other else ""
    return "; ".join(part for part in (text, note) if part)


def _failed(code: str, detail: str) -> Classified:
    return Classified(AuditStatus.FAILED, f"{code}: {detail}")


def _mismatch(target: AuditTarget, attempt: Attempt) -> str | None:
    if attempt.node_id != target.node_id or attempt.node.to_json() != target.node.to_json():
        return "the attempt is of another node"
    if attempt.cnf_sha256 != target.cnf_sha256:
        return "the regenerated CNF hash differs from the target's"
    if attempt.route != target.route:
        return f"route {attempt.route.value} instead of {Route(target.route).value}"
    return None


def classify_attempt(  # noqa: PLR0911 - one return per row of the module doc
    target: AuditTarget, attempt: Attempt, machinery: Machinery, admit: Admit
) -> Classified:
    """The status of ``target`` from its new attempt run under ``machinery`` (module doc)."""
    problem = _mismatch(target, attempt)
    if problem is not None:
        return _failed("attempt_mismatch", problem)
    outcome = attempt.outcome
    if outcome == Outcome.MODEL:
        return _failed(
            "inconsistent_model", "the solver found a valid model of a target used as proved"
        )
    if attempt.route == Route.CDCL and attempt.limits.solver_time_ms is not None:
        return _failed(
            "attempt_mismatch",
            "a CDCL audit attempt must have no solver time limit (solver_time_ms null)",
        )
    admission = admission_reason(admit, machinery)
    if admission is not None:
        return _failed(admission, "the audit machinery is not admitted by the campaign")
    if outcome == Outcome.INVALID_MODEL:
        error = attempt.model_error.value if attempt.model_error is not None else "unknown"
        return _failed("invalid_model", f"the solver reported an invalid model ({error})")
    if outcome == Outcome.TOOL_FAILED:
        return _failed("tool_failed", str(attempt.reason))
    if outcome == Outcome.CHECK_REJECTED:
        return _failed("rejected", "the admitted checker rejected the new proof")
    if outcome == Outcome.EXHAUSTED:
        return Classified(AuditStatus.OPEN, f"exhausted: {attempt.reason}")
    assert outcome == Outcome.VERIFIED_UNSAT
    same_hash = attempt.proof_sha256 == target.proof_sha256
    differences = profile_differences(target, machinery)
    if differences:
        text = (
            f"different profile ({', '.join(differences)}); a reproof, not a historical match; "
            f"proof hash {'equal' if same_hash else 'differs'}"
        )
        return Classified(AuditStatus.REPROVED_UNSAT, _with_reported(text, target, machinery))
    if same_hash:
        return Classified(AuditStatus.HASH_MATCHED, _with_reported("", target, machinery))
    text = f"proof_sha256 {attempt.proof_sha256} differs from {target.proof_sha256}"
    return Classified(AuditStatus.MISMATCH, _with_reported(text, target, machinery))


def strict_runnable(target: AuditTarget, solver_sha256: str, argv: Sequence[str]) -> bool:
    """Whether a strict audit can run ``target`` with the configured solver: unit targets
    always, CDCL targets only with the source binary and argv."""
    if Route(target.route) == Route.UNIT:
        return True
    source = target.machinery.solver
    return source.sha256 == solver_sha256 and tuple(source.argv) == tuple(argv)


def classify_unavailable(target: AuditTarget, machinery: Machinery) -> Classified:
    """NOT_COMPARABLE: a strict audit does not have the source solver of ``target``."""
    missing = [
        n for n in ("solver.sha256", "solver.argv") if n in profile_differences(target, machinery)
    ]
    text = f"source tools unavailable ({', '.join(missing) or 'solver'}); no reproof in strict mode"
    return Classified(AuditStatus.NOT_COMPARABLE, text)


def failure_code(reason: str) -> str:
    """The code of a FAILED reason (the text before the first ``": "``)."""
    return reason.split(": ", 1)[0]


def exit_class(status: AuditStatus, reason: str) -> int:
    """The exit code one result contributes (module doc; the report takes the most severe)."""
    status = AuditStatus(status)
    if status == AuditStatus.HASH_MATCHED:
        return int(ExitCode.SUCCESS)
    if status == AuditStatus.MISMATCH:
        return int(ExitCode.INTEGRITY)
    if status == AuditStatus.FAILED:
        code = failure_code(reason)
        return int(ExitCode.TOOL if code in TOOL_FAILURES else ExitCode.INTEGRITY)
    return int(ExitCode.OPEN)
