"""The generated application reference and the checks that keep its documentation honest.

``release docs`` writes ``docs/faces12/cli-reference.md`` from the command-line parser (it is
passed in: the command line sits above this adapter); ``release docs --check`` changes
nothing and reports

- a generated file that is out of date;
- an article reference ``(paper: label)`` in ``docs/faces12/`` or in the package's own sources
  that is not a ``\\label`` of the article;
- a relative link in ``docs/faces12/`` that points nowhere.
"""

from __future__ import annotations

import argparse
import re
from collections.abc import Iterable, Iterator, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Final

import faces12_campaign

__all__ = [
    "ARTICLE",
    "DOCS",
    "GENERATED_NOTE",
    "REFERENCE",
    "CommandLine",
    "article_labels",
    "check",
    "generated",
    "render_reference",
    "write",
]

ARTICLE: Final = "paper/faces12-en.tex"
DOCS: Final = "docs/faces12"
REFERENCE: Final = "docs/faces12/cli-reference.md"
GENERATED_NOTE: Final = (
    "Generated by `faces12-campaign release docs` from the command-line parser; do not edit."
)

_LABEL_TEXT = r"(?:thm|lem|cor|prop|def|hyp|rem|conv|sec|sub|app):[A-Za-z0-9-]+"
PAPER_REFERENCE: Final = re.compile(rf"paper:\s*({_LABEL_TEXT}(?:\s*,\s*{_LABEL_TEXT})*)")
_LABEL_DEF = re.compile(r"\\label\{([^}]+)\}")
_LINK = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")


@dataclass(frozen=True)
class CommandLine:
    """What the reference needs from the command line: its parser, the exit codes, and the
    commands that are delegated to cubeproof unchanged."""

    parser: argparse.ArgumentParser
    exit_codes: tuple[tuple[int, str], ...]
    delegated: tuple[str, ...]


def _table(header: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        cells = [str(cell).replace("|", "\\|").replace("\n", " ") for cell in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _subparsers(
    parser: argparse.ArgumentParser,
) -> argparse._SubParsersAction[argparse.ArgumentParser] | None:
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _commands(
    parser: argparse.ArgumentParser, prefix: str
) -> Iterator[tuple[str, str, argparse.ArgumentParser]]:
    action = _subparsers(parser)
    if action is None:
        return
    helps = {choice.dest: choice.help or "" for choice in action._choices_actions}
    for name, child in action.choices.items():
        yield f"{prefix} {name}", helps.get(name, ""), child
        yield from _commands(child, f"{prefix} {name}")


def _option_rows(parser: argparse.ArgumentParser) -> list[list[str]]:
    rows = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        if action.option_strings:
            name = ", ".join(f"`{o}`" for o in action.option_strings)
            if action.nargs != 0:
                name += f" `{action.metavar or action.dest.upper()}`"
        else:
            name = f"`{action.metavar or action.dest}`"
        default = ""
        if action.required:
            default = "required"
        elif action.nargs != 0 and action.default not in (None, "", [], (), argparse.SUPPRESS):
            default = f"`{action.default}`"
        meaning = action.help or ""
        if action.choices and not isinstance(action.choices, dict):
            meaning += (
                ("; " if meaning else "") + "one of " + ", ".join(f"`{c}`" for c in action.choices)
            )
        rows.append([name, default, meaning])
    return rows


def render_reference(cli: CommandLine) -> str:
    """The Markdown reference of the command line."""
    program = "faces12-campaign"
    out = [
        "# faces12-campaign command reference",
        "",
        f"<!-- {GENERATED_NOTE} -->",
        "",
        f"Version {faces12_campaign.__version__}. Run as `python -m faces12_campaign COMMAND ...`;",
        f"the program calls itself `{program}`. [The application guide](application.md)",
        "explains how the commands are used together.",
        "",
        "## Commands",
        "",
    ]
    for name, help_text, child in _commands(cli.parser, program):
        word = name.split()[1]
        out += [f"### `{name}`", ""]
        if help_text:
            out += [help_text[:1].upper() + help_text[1:] + ".", ""]
        if word in cli.delegated and name.count(" ") == 1:
            out += [
                f"Delegated unchanged to `cubeproof {word}`: every argument after `{word}` is",
                "passed through, and the options are those of the",
                "[cubeproof command reference](../cubeproof/cli-reference.md).",
                "",
            ]
            continue
        rows = _option_rows(child)
        if _subparsers(child) is not None:
            steps = ", ".join(f"`{n.split()[-1]}`" for n, _, _ in _commands(child, name))
            out += [f"Steps: {steps}.", ""]
        elif rows:
            out += [_table(["Option", "Default", "Meaning"], rows), ""]
    out += ["## Exit codes", ""]
    out += [_table(["Code", "Meaning"], [[f"`{c}`", m] for c, m in cli.exit_codes]), ""]
    return "\n".join(out)


def generated(cli: CommandLine) -> dict[str, str]:
    """Every generated file's content, by path relative to the source root."""
    return {REFERENCE: render_reference(cli)}


def write(cli: CommandLine, root: Path) -> list[str]:
    """Rewrite every generated file that is out of date; the paths written."""
    changed = []
    for path, content in generated(cli).items():
        target = Path(root) / path
        if not target.is_file() or target.read_text(encoding="utf-8") != content:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
            changed.append(path)
    return changed


def article_labels(root: Path) -> set[str]:
    """Every ``\\label`` of the article."""
    return set(_LABEL_DEF.findall((Path(root) / ARTICLE).read_text(encoding="utf-8")))


def _sources() -> list[Path]:
    package = Path(faces12_campaign.__file__).resolve().parent
    return sorted(p for p in package.rglob("*.py") if "__pycache__" not in p.parts)


def check(cli: CommandLine, root: Path) -> list[str]:
    """Every problem found (module doc), as a sentence; empty when consistent."""
    base = Path(root)
    problems = []
    for name, content in generated(cli).items():
        output = base / name
        if not output.is_file() or output.read_text(encoding="utf-8") != content:
            problems.append(f"{name} is out of date: run `faces12-campaign release docs`")
    labels = article_labels(base)
    documents = sorted((base / DOCS).glob("*.md"))
    named = [(f"{DOCS}/{p.name}", p) for p in documents]
    named += [(f"faces12_campaign/{p.name}", p) for p in _sources()]
    for where, path in named:
        for match in PAPER_REFERENCE.finditer(path.read_text(encoding="utf-8")):
            for label in re.findall(_LABEL_TEXT, match.group(1)):
                if label not in labels:
                    problems.append(f"{where}: `paper: {label}` is not a label of {ARTICLE}")
    for document in documents:
        for link in _LINK.findall(document.read_text(encoding="utf-8")):
            if re.match(r"[a-z]+:", link) or link.startswith("#"):
                continue
            if not (document.parent / link.split("#")[0]).exists():
                problems.append(f"{DOCS}/{document.name}: link to {link} is broken")
    return problems
